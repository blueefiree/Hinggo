async function main() {
  console.log("Seeding catalog Products and Admin user...");

  // Seed Admin user
  await prisma.user.upsert({
    where: { id: "user-admin" },
    update: {
      name: "Admin Hingo",
      role: "ADMIN",
      kycStatus: "VERIFIED",
      phoneVerified: true,
    },
    create: {
      id: "user-admin",
      name: "Admin Hingo",
      email: "admin@hingo.id",
      phone: "+6281200000001",
      city: "Jakarta Selatan",
      role: "ADMIN",
      phoneVerified: true,
      kycStatus: "VERIFIED",
    },
  });
  console.log("Admin user seeded successfully!");

  // Upsert products
  for (const p of PRODUCTS) {
    await prisma.product.upsert({
      where: { code: p.code },
      update: {
        slug: p.slug,
        brand: p.brand,
        name: p.name,
        subtitle: p.subtitle,
        category: p.category,
        condition: p.condition,
        usageDuration: p.usageDuration,
        switchOrVariant: p.switchOrVariant,
        completeness: p.completeness,
        description: p.description,
        defectNotes: p.defectNotes,
        price: p.price,
        originalNewPrice: p.originalNewPrice,
        rating: p.rating,
        soldCount: p.soldCount,
        stock: p.stock,
        location: p.location,
        isVerifiedByTeam: p.isVerifiedByTeam,
        images: p.images,
        status: p.status,
      },
      create: p,
    });
  }

  console.log(`Successfully seeded ${PRODUCTS.length} store catalog products!`);
}

main()
  .catch((e) => {
    console.error("Seeding error:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
